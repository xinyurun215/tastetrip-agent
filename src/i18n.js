let language = 'zh';
let chosen = false;
try {
  const saved = globalThis.localStorage?.getItem('tastetrip-language');
  if (saved === 'zh' || saved === 'en') { language = saved; chosen = true; }
} catch { /* Storage can be disabled; an explicit in-memory choice still works. */ }
export function hasLanguageChoice() { return chosen; }
export function getLanguage() { return language; }
export function chooseLanguage(value) {
  language = value === 'en' ? 'en' : 'zh';
  chosen = true;
  try { globalThis.localStorage?.setItem('tastetrip-language', language); } catch { /* optional persistence */ }
  return language;
}
export function t(key, values = {}) {
  return (language === 'en' ? en[key] || key : key).replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''));
}
